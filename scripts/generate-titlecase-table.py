#!/usr/bin/env python3
"""
Generates the Python text tables the Punctuation Restorer needs to match ekko-pnc's Python
reference (`ekko-stt[pnc]==0.1.2`, `ekko/pnc.py`) character for character.

Usage:
    python3 scripts/generate-titlecase-table.py

Writes two files:

  src/bun/utils/punctuation/python-text-tables.ts
      What the restorer imports: the characters Python's `str.split()` splits on, and the
      titlecase table - every code point whose `str.title()` differs from its `str.upper()`
      (`ﬁ` -> `Fi`, `ß` -> `Ss`, `ǆ` -> `ǅ`, ...). Everywhere else JavaScript's
      `toUpperCase()` already gives what Python's `title()` does.

  src/bun/utils/punctuation/fixtures/python-titlecase.json
      The test oracle: the same code points, each with what pnc.py 0.1.2's
      `_capitalize_initial_preserving_case` makes of the one-character word, computed by that
      function itself (copied below unchanged). The restorer's test feeds each one through the
      public interface and expects exactly this.

Re-run it when the Python that generates the ekko-pnc parity fixture moves to a newer Unicode
version, and commit both outputs together.
"""

import json
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TABLE_PATH = ROOT / "src/bun/utils/punctuation/python-text-tables.ts"
FIXTURE_PATH = ROOT / "src/bun/utils/punctuation/fixtures/python-titlecase.json"


# Verbatim from ekko-stt 0.1.2, ekko/pnc.py, Punctuator._capitalize_initial_preserving_case.
def _capitalize_initial_preserving_case(word: str) -> str:
    if any(character.isupper() or character.istitle() for character in word):
        return word
    for index, character in enumerate(word):
        if character.isalpha():
            return word[:index] + character.title() + word[index + 1 :]
    return word


def code_points():
    for code_point in range(0x110000):
        if 0xD800 <= code_point <= 0xDFFF:
            continue  # lone surrogates are not text
        yield code_point


def js_string(text: str) -> str:
    """A single-quoted JavaScript string literal with every character escaped."""
    parts = []
    for character in text:
        code_point = ord(character)
        if code_point > 0xFFFF:
            parts.append("\\u{%x}" % code_point)
        else:
            parts.append("\\u%04x" % code_point)
    return "'" + "".join(parts) + "'"


def main() -> None:
    python = "%d.%d.%d" % sys.version_info[:3]
    unicode_version = unicodedata.unidata_version

    whitespace = [chr(c) for c in code_points() if chr(c).isspace()]
    # str.split() with no argument splits on exactly what str.isspace() accepts.
    assert "a\x1cb".split() == ["a", "b"]

    titlecase = [
        chr(c) for c in code_points() if chr(c).title() != chr(c).upper()
    ]

    source = f"""/**
 * Python's text rules, as data, for the Punctuation Restorer.
 *
 * Generated by scripts/generate-titlecase-table.py from Python {python} (Unicode
 * {unicode_version}). Do not edit by hand; re-run the script.
 */

/** Every character Python's `str.split()` splits on (`str.isspace()`). */
export const PYTHON_WHITESPACE =
  {js_string("".join(whitespace))}

/**
 * Every code point whose Python `str.title()` differs from its `str.upper()`, with its
 * `str.title()`. For any other code point, `toUpperCase()` is the title case.
 */
export const TITLECASE_EXCEPTIONS: ReadonlyMap<string, string> = new Map([
"""
    for character in titlecase:
        source += f"  [{js_string(character)}, {js_string(character.title())}],\n"
    source += "])\n"
    TABLE_PATH.parent.mkdir(parents=True, exist_ok=True)
    TABLE_PATH.write_text(source, encoding="utf-8")

    fixture = {
        "generatedBy": "scripts/generate-titlecase-table.py",
        "python": python,
        "unicode": unicode_version,
        "codePoints": [
            {
                "codePoint": "U+%04X" % ord(character),
                "character": character,
                "title": character.title(),
                "upper": character.upper(),
                "capitalized": _capitalize_initial_preserving_case(character),
            }
            for character in titlecase
        ],
    }
    FIXTURE_PATH.parent.mkdir(parents=True, exist_ok=True)
    FIXTURE_PATH.write_text(
        json.dumps(fixture, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    print(f"{len(titlecase)} titlecase exceptions, {len(whitespace)} whitespace characters")


if __name__ == "__main__":
    main()
